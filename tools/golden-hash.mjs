/**
 * Cross-Node determinism gate (E6).
 *
 * The golden test proves two runs replay byte-identically IN ONE PROCESS. That
 * does not prove the same seed produces the same bytes on Node 20 vs 22 vs 24:
 * ICU collation (localeCompare), Math internals, and JSON key ordering can all
 * differ across majors. Every localeCompare in the deterministic path pins
 * "en" rather than the system default, but pinning is a precaution, not a
 * proof — so the proof is a committed hash.
 *
 * Usage: node tools/golden-hash.mjs [--write]
 *   default: run the fixed pipeline and compare against bench/golden-hash.txt
 *   --write: regenerate bench/golden-hash.txt (only when the engine
 *            intentionally changes output, and the diff must be reviewed)
 *
 * CI runs this on Node 20, 22, 24 × ubuntu/windows/macos. A red job means the
 * engine is not portable and the replay contract is narrower than claimed.
 */
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";
import { mkdtempSync, rmSync } from "node:fs";
import os from "node:os";
import path from "node:path";

const HERE = dirname(fileURLToPath(import.meta.url));
const HASH_FILE = join(HERE, "..", "bench", "golden-hash.txt");
const WRITE = process.argv.includes("--write");

// The engine is imported from the BUILT dist, the same artifact e2e and the
// cleanroom gate exercise. Run `npm run build` in murmur/ first (CI does).
// pathToFileURL because a bare Windows path is not a valid ESM specifier.
import { pathToFileURL } from "node:url";
const MURMUR = join(HERE, "..", "murmur");
const engine = await import(pathToFileURL(join(MURMUR, "packages", "engine", "dist", "index.js")).href);
const { runPipeline } = await import(pathToFileURL(join(MURMUR, "tests", "helpers", "pipeline.mjs")).href);

async function runOnce() {
  const dir = mkdtempSync(path.join(os.tmpdir(), "murmur-hash-"));
  try {
    // Fixed seed, fixed population, fixed rounds — the same run the golden
    // test replays, but hashed instead of compared in-process.
    const run = await runPipeline(engine, { cwd: dir, seed: "golden-hash-v1", rounds: 4, population: 12 });
    const dump = run.dump();
    run.close?.();
    return dump;
  } finally {
    rmSync(dir, { recursive: true, force: true });
  }
}

const dump = await runOnce();
const hash = createHash("sha256").update(dump, "utf8").digest("hex");
const record = `# MurmurBench golden hash. Generated by tools/golden-hash.mjs --write.
# seed=golden-hash-v1 rounds=4 population=12 node=${process.version} platform=${process.platform}
# Regenerate ONLY when the engine intentionally changes output, and review the
# diff: an unexpected hash change is a determinism regression, not housekeeping.
${hash} ${process.version} ${process.platform}
`;

if (WRITE) {
  writeFileSync(HASH_FILE, record);
  console.log(`wrote ${HASH_FILE}\n${hash} ${process.version} ${process.platform}`);
  process.exit(0);
}

if (!existsSync(HASH_FILE)) {
  console.error(`missing ${HASH_FILE} — run: node tools/golden-hash.mjs --write`);
  process.exit(1);
}

const expected = readFileSync(HASH_FILE, "utf8").split("\n").filter(Boolean).pop().split(" ")[0];
if (hash === expected) {
  console.log(`GOLDEN HASH GREEN — ${hash} (${process.version} ${process.platform})`);
} else {
  console.error(`GOLDEN HASH RED`);
  console.error(`  expected: ${expected} (committed)`);
  console.error(`  actual:   ${hash} (${process.version} ${process.platform})`);
  console.error(`The engine is not portable across this runtime. Do not regenerate`);
  console.error(`the hash to make CI green — find the divergence first.`);
  process.exit(1);
}
